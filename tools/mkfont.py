#!/usr/bin/env python3
"""Convert a TTF into a 1-bit C font table for app_gfx.

    ./tools/mkfont.py --font /usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf \
                      --size 48 --name big --chars '0123456789-.°C' \
                      --out components/app_gfx/font_big.c

Where:

- `--font` is any TTF FreeType can open. DejaVu ships with most Linux distributions and
  is licensed permissively, which matters while this project's own licence is undecided
- `--size` is the pixel size passed to FreeType, not the resulting line height; the
  generated `line_height` is what app_gfx actually uses to stack rows
- `--chars` is the exact set to include. Restricting it is the whole point at large sizes:
  the 48 px face needs digits, a minus, a full stop, a degree sign and a capital C, and
  the other ninety glyphs would be dead weight in the image
- `--out` is a C file; the matching declaration goes in `app_gfx_fonts.h` by hand, because
  a generated header that nobody reads is where stale declarations hide

The output is committed rather than generated during the build. A firmware build should
not require Pillow and FreeType on every machine that clones the repository, and the
glyphs only change when somebody deliberately re-runs this. Re-run it and commit the
result; the command that produced each file is written into its header comment.
"""

import argparse
import shlex
import sys

try:
    from PIL import Image, ImageDraw, ImageFont
except ImportError:
    sys.exit("error: Pillow is required.  pip install pillow")


def render_glyph(font, ch):
    """Rasterise one character to a tight 1-bit bitmap plus its metrics.

    Returns (rows, width, height, left, top, advance) where `rows` is a list of
    bytes objects, one per pixel row, each padded to a byte boundary.
    """
    # Rendered as 8-bit grey and thresholded here rather than asked for as mode "1".
    # Pillow stores a "1" image one byte per pixel internally, so bytes(mask) is NOT the
    # packed bitmap it looks like, and reading it as one produces glyphs that smear
    # sideways -- which is exactly what the first version of this script did.
    #
    # The panel has seven inks and no greys, so the threshold has to happen somewhere;
    # doing it once, here, keeps it out of every draw call.
    mask = font.getmask(ch, mode="L")
    w, h = mask.size
    bbox = font.getbbox(ch)
    advance = int(round(font.getlength(ch)))

    if w == 0 or h == 0:
        return [], 0, 0, 0, 0, advance

    grey = bytes(mask)
    stride = (w + 7) // 8
    rows = []
    for y in range(h):
        row = bytearray(stride)
        for x in range(w):
            if grey[y * w + x] >= 128:
                row[x >> 3] |= 0x80 >> (x & 7)
        rows.append(bytes(row))

    # `top` is stored relative to the BASELINE, negative upwards, so app_gfx can draw at
    # `baseline + top` with no font metric in the arithmetic. Pillow's getbbox measures
    # from the top of the line box instead, so the ascent comes off here -- once, at
    # build time, rather than in every glyph loop on the device.
    left = bbox[0]
    top = bbox[1] - font.getmetrics()[0]
    return rows, w, h, left, top, advance


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--font", required=True)
    ap.add_argument("--size", type=int, required=True)
    ap.add_argument("--name", required=True, help="C identifier suffix, e.g. 'big'")
    ap.add_argument("--chars",
                    default="".join(chr(c) for c in range(32, 127)) + "°²")
    ap.add_argument("--out", required=True)
    args = ap.parse_args()

    font = ImageFont.truetype(args.font, args.size)
    ascent, descent = font.getmetrics()

    chars = sorted(set(args.chars), key=ord)

    blob = bytearray()
    glyphs = []
    for ch in chars:
        rows, w, h, left, top, advance = render_glyph(font, ch)
        offset = len(blob)
        for row in rows:
            blob.extend(row)
        glyphs.append((ord(ch), offset, w, h, left, top, advance))

    ident = f"app_gfx_font_{args.name}"
    # --chars is recorded even when it is the default: without it the command in the
    # header regenerates a *different* file, which is worse than no command at all --
    # the 48 px face carries 14 glyphs and the default would give it 97.
    cmd = (f"./tools/mkfont.py --font {args.font} --size {args.size} "
           f"--name {args.name} --chars {shlex.quote(args.chars)} --out {args.out}")

    with open(args.out, "w", encoding="utf-8") as f:
        f.write(f"/* Generated by tools/mkfont.py -- do not edit.\n *\n")
        f.write(f" *   {cmd}\n *\n")
        f.write(f" * Source face: {args.font}\n")
        f.write(f" * {len(glyphs)} glyphs, {len(blob)} bytes of bitmap.\n")
        f.write(" *\n")
        f.write(" * These tables are glyph bitmaps rendered from the face named above, so they are\n")
        f.write(" * a derivative of it and carry its notice with them:\n")
        f.write(" *\n")
        f.write(" *   Copyright (c) 2003 by Bitstream, Inc. All Rights Reserved.\n")
        f.write(" *   Bitstream Vera is a trademark of Bitstream, Inc.\n")
        f.write(" *   DejaVu changes are in public domain.\n")
        f.write(" *\n")
        f.write(" * Full terms in components/app_gfx/FONT-LICENCE.txt. The licence requires the\n")
        f.write(" * notice to travel with every copy, which is why it is emitted here rather than\n")
        f.write(" * recorded once in a file nobody copies.\n */\n")
        f.write('#include "app_gfx_fonts.h"\n\n')

        f.write(f"static const uint8_t {ident}_bitmap[] = {{\n")
        for i in range(0, len(blob), 16):
            chunk = ", ".join(f"0x{b:02X}" for b in blob[i:i + 16])
            f.write(f"    {chunk},\n")
        f.write("};\n\n")

        f.write(f"static const app_gfx_glyph_t {ident}_glyphs[] = {{\n")
        f.write("    /* codepoint, offset, w, h, left, top, advance */\n")
        for cp, off, w, h, left, top, adv in glyphs:
            note = chr(cp) if 33 <= cp < 127 else f"U+{cp:04X}"
            f.write(f"    {{ {cp:5d}, {off:6d}, {w:3d}, {h:3d}, {left:4d}, "
                    f"{top:4d}, {adv:3d} }},  /* {note} */\n")
        f.write("};\n\n")

        f.write(f"const app_gfx_font_t {ident} = {{\n")
        f.write(f"    .bitmap      = {ident}_bitmap,\n")
        f.write(f"    .glyphs      = {ident}_glyphs,\n")
        f.write(f"    .glyph_count = {len(glyphs)},\n")
        f.write(f"    .line_height = {ascent + descent},\n")
        f.write(f"    .ascent      = {ascent},\n")
        f.write("};\n")

    print(f"{args.out}: {len(glyphs)} glyphs, {len(blob)} bytes bitmap, "
          f"line_height {ascent + descent}")


if __name__ == "__main__":
    main()
